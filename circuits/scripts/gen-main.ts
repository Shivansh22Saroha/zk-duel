/**
 * Generate circuits/main_<N>.circom from shared/constants.ts — the only place game constants
 * enter the circuit (NFR-6). The .circom templates themselves contain no game numbers.
 *
 *   npx tsx circuits/scripts/gen-main.ts 60
 */
import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  ANGLE_UNITS,
  ARENA_H,
  ARENA_W,
  FIRE_COOLDOWN,
  MAG_SIZE,
  MAX_SPEED,
  MAX_TURN,
  PLAYER_RADIUS,
  RELOAD_TICKS,
  WINDOW_TICKS_VARIANTS,
} from '@zkduel/shared/constants';

export const CIRCUITS_DIR = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** Window(...) template parameters in declaration order (circuits/window.circom). */
export function windowParams(n: number): number[] {
  return [
    n,
    ARENA_W,
    ARENA_H,
    PLAYER_RADIUS,
    MAX_SPEED,
    ANGLE_UNITS,
    MAX_TURN,
    MAG_SIZE,
    FIRE_COOLDOWN,
    RELOAD_TICKS,
  ];
}

/** Public inputs as declared in main (the output commitOut is public implicitly). */
export const MAIN_PUBLIC_INPUTS = ['bind', 'digest', 'commitIn'] as const;

export function genMain(n: number): string {
  if (!(WINDOW_TICKS_VARIANTS as readonly number[]).includes(n)) {
    throw new Error(`N=${n} is not in WINDOW_TICKS_VARIANTS (${WINDOW_TICKS_VARIANTS.join(', ')})`);
  }
  const path = join(CIRCUITS_DIR, `main_${n}.circom`);
  const src = [
    'pragma circom 2.2.0;',
    '',
    '// GENERATED by circuits/scripts/gen-main.ts from shared/constants.ts — do not edit.',
    '// Window(N, ARENA_W, ARENA_H, PLAYER_RADIUS, MAX_SPEED, ANGLE_UNITS, MAX_TURN, MAG_SIZE, FIRE_COOLDOWN, RELOAD_TICKS)',
    'include "window.circom";',
    '',
    `component main {public [${MAIN_PUBLIC_INPUTS.join(', ')}]} = Window(${windowParams(n).join(', ')});`,
    '',
  ].join('\n');
  writeFileSync(path, src);
  return path;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const n = Number(process.argv[2] ?? 60);
  console.log(genMain(n));
}
